-- =====================================================
-- PIZZA SALES ANALYSIS
-- SQL Server Management Studio (SSMS)
-- Objective: Analyze pizza sales performance,
-- revenue, orders, quantity and customer preferences.
-- =====================================================


-- 1. TOTAL REVENUE
-- Calculate the total revenue generated from pizza sales.

SELECT
    SUM(total_price) AS Total_Revenue
FROM pizza_sales;


-- 2. AVERAGE ORDER VALUE (AOV)
-- Calculate the average revenue generated per order.

SELECT
    (SUM(total_price) / COUNT(DISTINCT order_id)) AS Avg_Order_Value
FROM pizza_sales;


-- 3. TOTAL PIZZAS SOLD
-- Calculate the total quantity of pizzas sold.

SELECT
    SUM(quantity) AS Total_Pizza_Sold
FROM pizza_sales;


-- 4. TOTAL ORDERS
-- Count the total number of unique orders received.

SELECT
    COUNT(DISTINCT order_id) AS Total_Orders
FROM pizza_sales;


-- 5. AVERAGE PIZZAS PER ORDER
-- Calculate the average number of pizzas purchased per order.
-- CAST is used to display the result with two decimal places.

SELECT
    CAST(
        CAST(SUM(quantity) AS DECIMAL(10,2)) /
        CAST(COUNT(DISTINCT order_id) AS DECIMAL(10,2))
        AS DECIMAL(10,2)
    ) AS Avg_Pizzas_Per_Order
FROM pizza_sales;


-- 6. DAILY TREND FOR TOTAL ORDERS
-- Identify the number of orders received on each day of the week.

SELECT
    DATENAME(DW, order_date) AS Order_Day,
    COUNT(DISTINCT order_id) AS Total_Orders
FROM pizza_sales
GROUP BY DATENAME(DW, order_date);


-- 7. MONTHLY TREND FOR TOTAL ORDERS
-- Analyze the number of orders received in each month.

SELECT
    DATENAME(MONTH, order_date) AS Month_Name,
    COUNT(DISTINCT order_id) AS Total_Orders
FROM pizza_sales
GROUP BY DATENAME(MONTH, order_date);


-- 8. SALES PERFORMANCE BY PIZZA CATEGORY
-- Calculate total revenue and revenue percentage
-- contributed by each pizza category.

SELECT
    pizza_category,
    CAST(SUM(total_price) AS DECIMAL(10,2)) AS Total_Revenue,
    CAST(
        SUM(total_price) * 100 /
        (SELECT SUM(total_price) FROM pizza_sales)
        AS DECIMAL(10,2)
    ) AS PCT
FROM pizza_sales
GROUP BY pizza_category;


-- 9. SALES PERFORMANCE BY PIZZA SIZE
-- Calculate total revenue and revenue percentage
-- generated by each pizza size.

SELECT
    pizza_size,
    CAST(SUM(total_price) AS DECIMAL(10,2)) AS Total_Revenue,
    CAST(
        SUM(total_price) * 100 /
        (SELECT SUM(total_price) FROM pizza_sales)
        AS DECIMAL(10,2)
    ) AS PCT
FROM pizza_sales
GROUP BY pizza_size
ORDER BY pizza_size;


-- 10. TOTAL PIZZAS SOLD BY CATEGORY IN FEBRUARY
-- Analyze pizza category performance for February.
-- MONTH(order_date) = 2 represents February.

SELECT
    pizza_category,
    SUM(quantity) AS Total_Quantity_Sold
FROM pizza_sales
WHERE MONTH(order_date) = 2
GROUP BY pizza_category
ORDER BY Total_Quantity_Sold DESC;


-- 11. TOP 5 PIZZAS BY REVENUE
-- Identify the five highest revenue-generating pizzas.

SELECT TOP 5
    pizza_name,
    SUM(total_price) AS Total_Revenue
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Revenue DESC;


-- 12. BOTTOM 5 PIZZAS BY REVENUE
-- Identify the five lowest revenue-generating pizzas.

SELECT TOP 5
    pizza_name,
    SUM(total_price) AS Total_Revenue
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Revenue ASC;


-- 13. TOP 5 PIZZAS BY QUANTITY SOLD
-- Identify the five most popular pizzas based on quantity sold.

SELECT TOP 5
    pizza_name,
    SUM(quantity) AS Total_Pizza_Sold
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Pizza_Sold DESC;


-- 14. BOTTOM 5 PIZZAS BY QUANTITY SOLD
-- Identify the five least popular pizzas based on quantity sold.

SELECT TOP 5
    pizza_name,
    SUM(quantity) AS Total_Pizza_Sold
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Pizza_Sold ASC;


-- 15. TOP 5 PIZZAS BY TOTAL ORDERS
-- Identify the five pizzas that appear in the highest
-- number of unique orders.

SELECT TOP 5
    pizza_name,
    COUNT(DISTINCT order_id) AS Total_Orders
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Orders DESC;


-- 16. BOTTOM 5 PIZZAS BY TOTAL ORDERS
-- Identify the five pizzas that appear in the lowest
-- number of unique orders.

SELECT TOP 5
    pizza_name,
    COUNT(DISTINCT order_id) AS Total_Orders
FROM pizza_sales
GROUP BY pizza_name
ORDER BY Total_Orders ASC;